import { mkdtemp, mkdir, writeFile, rm, readFile } from "node:fs/promises";
import { mkdtempSync, symlinkSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  openVerifiedArchive,
  inspectArchive,
  extractVerifiedArchive,
} from "./archive-policy";
const probe = mkdtempSync(path.join(tmpdir(), "fs-link-probe-"));
let fileLinks = true;
try {
  writeFileSync(path.join(probe, "file"), "x");
  symlinkSync(path.join(probe, "file"), path.join(probe, "link"), "file");
} catch (e: any) {
  if (e.code !== "EPERM" && e.code !== "EACCES") throw e;
  fileLinks = false;
} finally {
  rmSync(probe, { recursive: true, force: true });
}
(fileLinks ? test : test.skip)(
  "real file symlink source is rejected (privilege-dependent fixture)",
  async () => {
    const dir = await mkdtemp(path.join(tmpdir(), "fs-file-link-"));
    try {
      await writeFile(path.join(dir, "file"), "ok");
      symlinkSync(path.join(dir, "file"), path.join(dir, "link"), "file");
      await expect(
        openVerifiedArchive(
          path.join(dir, "link"),
          createHash("sha256").update("ok").digest("hex"),
        ),
      ).rejects.toThrow();
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  },
);
test.each(["windows-x64", "linux-x64"])(
  "round trips bytes generated by the actual publisher: %s",
  async (platform) => {
    const dir = await mkdtemp(path.join(tmpdir(), "fs-publisher-"));
    try {
      const source = path.join(dir, "source");
      for (const name of [
        "apps/server/dist/main.js",
        "apps/updater/dist/cli.js",
        "apps/updater/dist/launcher.js",
        "apps/web/dist/index.html",
        "packages/shared/dist/index.js",
        "packages/update-core/dist/index.js",
        "node_modules/example/index.js",
        "package.json",
        "package-lock.json",
        "apps/server/package.json",
        "apps/updater/package.json",
        "apps/web/package.json",
        "packages/shared/package.json",
        "packages/update-core/package.json",
        "scripts/release/smoke-artifact.mjs",
        "scripts/release/create-smoke-db.mjs",
        "scripts/release/validate-version.mjs",
        "scripts/release/start-artifact.mjs",
        "scripts/bootstrap-update.ps1",
        "scripts/bootstrap-update.sh",
        "scripts/start-filestation.ps1",
        "scripts/start-filestation.sh",
      ]) {
        await mkdir(path.dirname(path.join(source, name)), { recursive: true });
        await writeFile(path.join(source, name), "ok");
      }
      const publisher = pathToFileURL(
        path.resolve(
          __dirname,
          "../../../scripts/release/package-artifact.mjs",
        ),
      ).href;
      const script = `import {packageArtifact} from ${JSON.stringify(publisher)}; console.log(JSON.stringify(await packageArtifact(JSON.parse(process.argv[1]))));`;
      const result = JSON.parse(
        execFileSync(
          process.execPath,
          [
            "--input-type=module",
            "-e",
            script,
            JSON.stringify({
              sourceRoot: source,
              outputDirectory: dir,
              version: "0.2.5",
              platform,
              sourceDateEpoch: 1750000000,
            }),
          ],
          { encoding: "utf8" },
        ),
      );
      const h = await openVerifiedArchive(result.archivePath, result.sha256);
      try {
        const p = await inspectArchive(h, {
          format: result.format,
          version: "0.2.5",
          platform,
          unpackedSize: result.unpackedSize,
        });
        await extractVerifiedArchive(h, p, path.join(dir, "out"));
        expect(
          await readFile(
            path.join(dir, "out", "apps/server/dist/main.js"),
            "utf8",
          ),
        ).toBe("ok");
      } finally {
        await h.close();
      }
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  },
);
