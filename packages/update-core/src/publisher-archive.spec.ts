const probe = mkdtempSync(path.join(tmpdir(), "fs-link-probe-"));
let fileLinks = true;
try {
  writeFileSync(path.join(probe, "file"), "x");
  symlinkSync(path.join(probe, "file"), path.join(probe, "link"), "file");
} catch (e: any) {
  if (e.code !== "EPERM" && e.code !== "EACCES") throw e;
  fileLinks = false;
} finally {
  rmSync(probe, { recursive: true, force: true });
}
(fileLinks ? test : test.skip)(
  "real file symlink source is rejected (privilege-dependent fixture)",
  async () => {
    const dir = await mkdtemp(path.join(tmpdir(), "fs-file-link-"));
    try {
      await writeFile(path.join(dir, "file"), "ok");
      symlinkSync(path.join(dir, "file"), path.join(dir, "link"), "file");
      await expect(
        openVerifiedArchive(
          path.join(dir, "link"),
          createHash("sha256").update("ok").digest("hex"),
        ),
      ).rejects.toThrow();
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  },
);
